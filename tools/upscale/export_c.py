#!/usr/bin/env python3
"""Write a trained network (train.py's .pt) as port/upscale/upscale_weights.h (docs/port/UPSCALE.md).

    export_c.py --model net.pt [--out port/upscale/upscale_weights.h] [--name NAME]

Each convolution's weights go out as [ky][kx][in][out] (the output channel innermost, as upscale.c's loops read
them), in decimal with 9 significant digits, which gives back the same float32. Without --model: an untrained
network (its last layer is zero, so it is exactly Catmull-Rom), for building before any training.
"""
import argparse
import os
import sys

import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import Net  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def floats(t, per_line=8):
    v = [f"{x:.9g}f" if x != 0 else "0.0f" for x in t.detach().reshape(-1).tolist()]
    v = [s if any(c in s for c in ".en") else s[:-1] + ".0f" for s in v]   # 1f is not a C literal
    return ",\n".join("    " + ", ".join(v[i:i + per_line]) for i in range(0, len(v), per_line))


def conv(w):
    """PyTorch (out, in, ky, kx) -> (ky, kx, in, out)."""
    return w.permute(2, 3, 1, 0).contiguous()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model")
    ap.add_argument("--out", default=os.path.join(ROOT, "port", "upscale", "upscale_weights.h"))
    ap.add_argument("--name", help="model name for the logs (default: from the file)")
    args = ap.parse_args()
    if args.model:
        ck = torch.load(args.model, map_location="cpu")
        net = Net(ck["channels"], ck["blocks"])
        net.load_state_dict(ck["state"])
        name = args.name or (f"{os.path.splitext(os.path.basename(args.model))[0]} {ck['iters']} steps, "
                             f"val {ck['val_psnr']:.2f} dB (Catmull-Rom {ck['val_cubic_psnr']:.2f})")
    else:
        net = Net(16, 4)
        name = args.name or "untrained (Catmull-Rom)"
    c, n = net.channels, net.blocks
    out = []
    w = out.append
    w("/* port/upscale/upscale_weights.h: the 2x texture network's weights (docs/port/UPSCALE.md).")
    w(f" * Generated by tools/upscale/export_c.py: {name}. Do not edit; train and export again. */")
    w(f"#define UPS_CHANNELS {c}")
    w(f"#define UPS_BLOCKS {n}")
    w(f"#define UPS_MODEL_NAME \"{name}\"")
    w(f"#define UPS_MODEL_PARAMS {net.params()}")
    w("/* UPS_ALIGN (upscale.c): 16-byte alignment, for loading four channels at a time */")
    w("")
    w(f"static const float ups_head_w[3 * 3 * 3 * UPS_CHANNELS] UPS_ALIGN = {{\n{floats(conv(net.head.weight))}\n}};")
    w(f"static const float ups_head_b[UPS_CHANNELS] UPS_ALIGN = {{\n{floats(net.head.bias)}\n}};")
    w(f"static const float ups_head_a[UPS_CHANNELS] UPS_ALIGN = {{\n{floats(net.head_act.weight)}\n}};")
    w(f"static const float ups_body_w[UPS_BLOCKS][3 * 3 * UPS_CHANNELS * UPS_CHANNELS] UPS_ALIGN = {{")
    w(",\n".join(f"  {{\n{floats(conv(b.weight))}\n  }}" for b in net.body) + "\n};")
    w(f"static const float ups_body_b[UPS_BLOCKS][UPS_CHANNELS] UPS_ALIGN = {{")
    w(",\n".join(f"  {{\n{floats(b.bias)}\n  }}" for b in net.body) + "\n};")
    w(f"static const float ups_body_a[UPS_BLOCKS][UPS_CHANNELS] UPS_ALIGN = {{")
    w(",\n".join(f"  {{\n{floats(a.weight)}\n  }}" for a in net.body_act) + "\n};")
    w(f"static const float ups_tail_w[3 * 3 * UPS_CHANNELS * 12] UPS_ALIGN = {{\n{floats(conv(net.tail.weight))}\n}};")
    w(f"static const float ups_tail_b[12] UPS_ALIGN = {{\n{floats(net.tail.bias)}\n}};")
    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{args.out}: {net.params()} parameters ({name})", file=sys.stderr)


if __name__ == "__main__":
    main()
