#!/usr/bin/env python3
"""Generate per-file `#pragma weak` headers so every game symbol has exactly one strong definition.

    python3 tools/port/gen_weak.py --objects-list build/pc/probe_objects.txt --out-dir build/pc/weak

Many decompilation files define functions they don't own. A group compiles copies of its callees as context
for IDO's interprocedural optimizer, and some singles carry stand-ins. The N64 build never links those copies:
it places each function's bytes from the file the manifest names (manifest/*.json). Linked natively, they
collide. This tool reads which symbols each file defines (nm over the probe build's objects) and, for each
file, writes a header of `#pragma weak NAME` lines for the symbols it defines but doesn't own. The game build
force-includes it (-include), so the linker binds every call, including calls inside the copying file, to the
owner's definition. The compiler doesn't inline weak functions, so this holds with optimization on.

Ownership: a function's owner is the file the manifest names (singles' `source`, groups' files for their
`members`, static.json's `tu`). A symbol with no manifest owner (helpers, data) keeps its first definition in
path order, and the others are reported. Headers are rewritten only when their contents change, so a rebuild
doesn't recompile untouched files. Writes report.txt next to the headers. Stdlib only, Python 3.9+.
"""
import argparse
import collections
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import n64syms  # noqa: E402

_PROBE_OBJ = re.compile(r"[\\/]probe[\\/](.+)\.c\.(?:o|obj)$")


def source_id(rel_path):
    """src/blob/foo.c -> src__blob__foo (the probe wrapper and header name)."""
    return rel_path[:-2].replace("/", "__") if rel_path.endswith(".c") else rel_path.replace("/", "__")


def manifest_owners(root):
    """function name -> set of owning source paths (repo-relative)."""
    owners = collections.defaultdict(set)
    for image in ("game", "ovl_a", "ovl_b"):
        d = json.loads((root / "manifest" / f"{image}.json").read_text())
        for name, e in d["singles"].items():
            owners[name].add(e["source"])
        for e in d["groups"].values():
            files = {f"{e['dir']}/{f}" for f in e["files"]}
            for m in e["members"]:
                owners[m] |= files
    for name, e in json.loads((root / "manifest" / "static.json").read_text())["c"].items():
        owners[name].add(e["tu"])
    return owners


def defined_symbols(obj, nm):
    """Strong global definitions in one object (common symbols are mergeable and left alone). Names starting with
    a dot are the compiler's, not C's: PE objects define a `.refptr.X` slot for every extern X they use."""
    out = subprocess.run([nm, "-g", "--defined-only", str(obj)], capture_output=True, text=True, check=True).stdout
    return {p[2] for p in (l.split() for l in out.splitlines())
            if len(p) == 3 and p[1] in "TDBRS" and not p[2].startswith(".")}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--objects-list", type=Path, required=True, help="probe objects, one per line")
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--nm", default="nm")
    ap.add_argument("--root", type=Path, default=n64syms.ROOT)
    ap.add_argument("--pe", action="store_true", help="Windows: also give each header a global of its file's own")
    a = ap.parse_args()

    owners = manifest_owners(a.root)
    probe_dir = a.objects_list.parent / "probe"
    files = {}   # id -> repo-relative source path
    defs = {}    # id -> set of symbols
    for line in a.objects_list.read_text().split():
        m = _PROBE_OBJ.search(line)
        if not m:
            continue
        sid = m.group(1).replace("\\", "/").split("/")[-1]
        wrapper = (probe_dir / f"{sid}.c").read_text()
        src = Path(wrapper.split('"')[1]).resolve().relative_to(a.root.resolve()).as_posix()
        files[sid], defs[sid] = src, defined_symbols(line, a.nm)

    where = collections.defaultdict(list)
    for sid in sorted(files, key=lambda s: files[s]):
        for name in defs[sid]:
            where[name].append(sid)
    weak = collections.defaultdict(set)
    unowned_dups, owner_missing = [], []
    for name, sids in where.items():
        own = [s for s in sids if files[s] in owners.get(name, ())]
        if own:
            strong = own[0]
        else:
            strong = sids[0]
            if name in owners and len(sids) > 1:
                owner_missing.append(name)
            elif len(sids) > 1:
                unowned_dups.append(name)
        for s in sids:
            if s != strong:
                weak[s].add(name)

    a.out_dir.mkdir(parents=True, exist_ok=True)
    changed = 0
    for sid in files:
        text = (f"/* {files[sid]}: generated by tools/port/gen_weak.py. Symbols this file defines but the manifest"
                f" gives to another file. */\n" + "".join(f"#pragma weak {n}\n" for n in sorted(weak[sid])))
        if a.pe and weak[sid]:
            # GNU as on PE names a weak definition's body `.weak.<name>.<a global the file defines>`, the first it
            # meets: in a file whose globals are all weak copies that is `.weak.<name>.`, the same in every such file.
            # The anchor must come first: no_reorder keeps it there when GCC reorders top-level definitions (-O1
            # on), which made two copies of one group file both name their bodies after a common they share.
            text += (f"/* PE: a global of this file's own, which the weak definitions' bodies are named after. */\n"
                     f"__attribute__((no_reorder)) char pc_weak_anchor_{re.sub(r'[^A-Za-z0-9_]', '_', sid)} = 0;\n")
        path = a.out_dir / f"{sid}.h"
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed += 1
    total = sum(len(v) for v in weak.values())
    report = [f"{total} weak definitions in {sum(1 for v in weak.values() if v)} files; {changed} headers rewritten.",
              f"Owned by a file that doesn't define them (first copy kept): {len(owner_missing)}",
              *(f"  {n}: {', '.join(files[s] for s in where[n])}" for n in sorted(owner_missing)),
              f"Defined in several files, no manifest owner (first kept): {len(unowned_dups)}",
              *(f"  {n}: {', '.join(files[s] for s in where[n])}" for n in sorted(unowned_dups))]
    (a.out_dir / "report.txt").write_text("\n".join(report) + "\n")
    print(f"gen_weak: {report[0]} {len(owner_missing)} owner-missing, {len(unowned_dups)} unowned duplicates")


if __name__ == "__main__":
    main()
