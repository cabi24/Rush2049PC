#!/usr/bin/env python3
"""Generate bss.c: definitions for the boot and game BSS symbols the game C declares but nothing defines.

    python3 tools/port/gen_bss.py --objects-list build/pc/game_objects.txt --out build/pc/pc-data/bss.c [--nm nm]

On the N64 these symbols are absolute addresses (undefined_syms_auto.us.txt). Here each BSS region becomes one
zeroed array laid out like the N64's, and every symbol in it is defined at its N64 offset with an assembler
`.set`. Code that walks from one symbol into the next, or names an address inside another object, keeps
working.

Exception: a symbol any file declares with a pointer type gets its own storage (`void *name[n]`, n = its N64
size / 4). A native pointer is 8 bytes and would overwrite the next N64 slot. Symbols sharing its address are
set to that storage. The list is printed and kept in bss.c's header, because code that reaches those objects
through a neighbor's address breaks; struct types that hold pointers are not detected and are Phase 2 work
(docs/PORT_PLAN.md).

Overlay BSS is not handled here: both runtime images use 0x8038A400, so it needs the overlay design. Stdlib
only, Python 3.9+.
"""
import argparse
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import n64syms  # noqa: E402

_IDENT = re.compile(r"[A-Za-z_]\w*")


def pointer_declarations(src, names):
    """name -> Counter{'pointer': n, 'value': n} from the extern declarations under src/."""
    found = collections.defaultdict(collections.Counter)
    for path in sorted(Path(src).rglob("*.c")):
        for line in path.read_text(errors="replace").splitlines():
            if not line.startswith("extern"):
                continue
            decl = line.split(";", 1)[0]
            for m in _IDENT.finditer(decl):
                if m.group(0) not in names:
                    continue
                head = decl[:m.start()]
                segment = head[head.rfind(",") + 1:] if "," in head else head
                found[m.group(0)]["pointer" if "*" in segment else "value"] += 1
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--objects-list", type=Path, required=True, help="the game objects, one per line")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--nm", default="nm")
    ap.add_argument("--root", type=Path, default=n64syms.ROOT)
    a = ap.parse_args()

    syms = n64syms.load_symbols(a.root / "symbol_addrs.us.txt")
    _, undefined = n64syms.nm_symbols(a.objects_list.read_text().split(), a.nm)
    by_region = {r: collections.defaultdict(list) for r in n64syms.BSS_REGIONS}   # region -> addr -> names
    for name in sorted(undefined):
        addr = n64syms.address_of(name, syms)
        if addr is None or n64syms.kind_of(name, syms) != "data":
            continue
        region = n64syms.region_of(addr)
        if region in by_region:
            by_region[region][addr].append(name)
    names = {n for r in by_region.values() for ns in r.values() for n in ns}
    decls = pointer_declarations(a.root / "src", names)

    # Every known address in each region, for sizes: symbol-file size, else the gap to the next address.
    known = collections.defaultdict(set)
    for name, (addr, _, _) in syms.items():
        region = n64syms.region_of(addr)
        if region in by_region:
            known[region].add(addr)
    for region, addrs in by_region.items():
        known[region].update(addrs)

    def n64_size(region, addr, group):
        sizes = [syms[n][2] for n in group if n in syms and syms[n][2]]
        if sizes:
            return max(sizes)
        hi = n64syms.BSS_REGIONS[region][1]
        later = [x for x in known[region] if x > addr]
        return (min(later) if later else hi) - addr

    arenas, sets, own, mixed = [], [], [], []
    for region, groups in by_region.items():
        lo, hi = n64syms.BSS_REGIONS[region]
        arena = "pc_n64_" + region.replace(" ", "_")
        arenas.append((arena, lo, hi))
        for addr in sorted(groups):
            group = sorted(groups[addr])
            kinds = collections.Counter()
            for n in group:
                kinds.update(decls.get(n, {}))
            if kinds["pointer"]:
                if kinds["value"]:
                    mixed.append(group[0])
                count = max(1, n64_size(region, addr, group) // 4)
                own.append((group[0], count, addr))
                sets += [(n, group[0], 0) for n in group[1:]]
            else:
                sets += [(n, arena, addr - lo) for n in group]

    L = ["/* bss.c: generated by tools/port/gen_bss.py. Do not edit; rebuild regenerates it.",
         f" * {len(sets) + len(own)} boot and game BSS symbols: {len(sets)} at their N64 offsets in the arenas below,",
         f" * {len(own)} pointer-typed with their own storage"
         + (f" ({len(mixed)} also declared as non-pointers somewhere)." if mixed else "."),
         " * Pointer-typed: " + " ".join(f"{n}" for n, _, _ in own) + " */", "",
         "#include <stdint.h>", "",
         "#if defined(__APPLE__)", "#define N64_SYM(name) \"_\" name", "#else", "#define N64_SYM(name) name",
         "#endif", ""]
    for arena, lo, hi in arenas:
        L.append(f"__attribute__((aligned(16))) uint8_t {arena}[0x{hi - lo:X}];   /* N64 0x{lo:08X}-0x{hi:08X} */")
    L.append("")
    for name, count, addr in own:
        L.append(f"void *{name}[{count}];   /* N64 0x{addr:08X} */")
    if sets:
        L += ["", "__asm__("]
        for name, base, off in sets:
            L.append(f"    \".globl \" N64_SYM(\"{name}\") \"\\n.set \" N64_SYM(\"{name}\") \", \" N64_SYM(\"{base}\")"
                     f" \" + 0x{off:X}\\n\"")
        L += [");", ""]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(L))
    print(f"gen_bss: {len(sets) + len(own)} symbols ({len(own)} pointer-typed, {len(mixed)} mixed) -> {a.out}")


if __name__ == "__main__":
    main()
