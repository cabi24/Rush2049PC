#!/usr/bin/env python3
"""Write the make rules that compile the C of the three compressed images.

    python3 tools/gen_rules.py > build/rules.mk

One rule per single (manifest/<image>.json "singles": its own flags) and one
per whole-program group. Defines GAME_OBJS, OVL_A_OBJS, OVL_B_OBJS.
"""
import json
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    out = ["# Generated by tools/gen_rules.py from manifest/*.json; do not edit."]
    for image, var in (("game", "GAME_OBJS"), ("ovl_a", "OVL_A_OBJS"), ("ovl_b", "OVL_B_OBJS")):
        m = json.loads((ROOT / "manifest" / f"{image}.json").read_text())
        objs = []
        for fn, rec in sorted(m["singles"].items()):
            obj = f"build/{image}/obj/{fn}.o"
            objs.append(obj)
            out += [f"{obj}: {rec['source']} manifest/{image}.json",
                    f"\t@echo \"CC {rec['source']}\"",
                    f"\t$(V)tools/compile_single.sh $(IDO53_CC) {fn} {rec['source']} $@ "
                    + " ".join(shlex.quote(f) for f in rec["flags"].split())]
        for group, rec in sorted(m["groups"].items()):
            obj = f"build/{image}/groups/{group}.o"
            objs.append(obj)
            deps = " ".join(f"{rec['dir']}/{f}" for f in ["group.json"] + rec["files"])
            out += [f"{obj}: {deps} manifest/{image}.json",
                    f"\t@echo \"CC (group, -O3 IPA) {rec['dir']}\"",
                    f"\t$(V)$(PYTHON) tools/compile_group.py $(IDO53_DIR) {rec['dir']} $@"]
        out.append(f"{var} := " + " \\\n    ".join(objs))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
