int pc_gfx_font_glyph(int c, uint8_t rows[PC_GFX_FONT_H]) {
    int i = c - 32, r, x;
    const char *line;
    if (i < 0 || i >= 95)
        return 0;
    for (r = 0; r < PC_GFX_FONT_H; r++) {
        line = font[i / BAND * PC_GFX_FONT_H + r] + i % BAND * (PC_GFX_FONT_W + 1);
        rows[r] = 0;
        for (x = 0; x < PC_GFX_FONT_W; x++)
            rows[r] = (uint8_t)(rows[r] << 1 | (line[x] == '#'));
    }
    return 1;
}
